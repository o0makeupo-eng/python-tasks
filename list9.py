#Дан список A из N чисел. Вывести элементы, большие среднего арифметического всех
#элементов, и их количество

n = int(input())
a = []

for i in range(n):
    a.append(int(input()))

c = sum(a) / len(a)
print(f"Среднее арифметическое: {c}")

k = 0

for i in a:
    if i > c:
        print(f"Элементы большие среднего арифметического: {i}")
        k += 1
print(f"Количество элемонтов большие ср арифметического: {k}")