#Прочитать два целых числа и вывести их частное с одним знаком после точки. При делении на ноль
#вывести «Делить на ноль нельзя». Нечисловой ввод обрабатывать не требуется.
try: 
    a, b = int(input()), int(input())
    print(round(a / b, 2))
except ZeroDivisionError:
    print("Делить на ноль нельзя")