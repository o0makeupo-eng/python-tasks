#Дан список из N строк. Вывести самую длинную и самую короткую строку (первую из
#встретившихся) и их длины


N = ["о", "дд", "ттт", "чччч", "ппппп"]
imax = 0
imin = 0 
for i in range(len(N)):
    if N[i] > N[imax]:
        imax = i 
    elif N[i] < N[imin]:
        imin = i 
print(f"Самая длинная строка: {N[imax]}")
print(f"Длина самой длинной строки: {len(N[imax])}")

print(f"Самая короткая строка: {N[imin]}")
print(f"Длина самой короткой строки: {len(N[imin])}")